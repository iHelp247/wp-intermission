/* Unmissable admin-bar badge while maintenance mode is on — with a live
 * countdown beside it when a future target is set. */
function ih247_wpim_admin_bar( $bar ) {
	if ( ! ih247_wpim_is_enabled() || ! current_user_can( 'manage_options' ) ) {
		return;
	}
	$title = '<span style="background:#d63638;color:#fff;padding:0 8px;border-radius:2px;">' . esc_html__( 'MAINTENANCE ON', 'wp-intermission' ) . '</span>';

	$ts = ih247_wpim_countdown_ts();
	if ( $ts && $ts > time() ) {
		$title .= ' <span id="ih-abar-cd" data-t="' . esc_attr( $ts * 1000 ) . '"'
			. ' style="background:#1d2327;color:#fff;padding:0 8px;border-radius:2px;font-variant-numeric:tabular-nums;">…</span>';
	}

	$bar->add_node(
		array(
			'id'    => 'wp-intermission',
			'title' => $title,
			'href'  => admin_url( 'options-general.php?page=wp-intermission' ),
		)
	);
}
add_action( 'admin_bar_menu', 'ih247_wpim_admin_bar', 100 );

/** Tick the admin-bar countdown (front-end and wp-admin alike). */
function ih247_wpim_admin_bar_script() {
	if ( ! is_admin_bar_showing() ) {
		return;
	}
	echo '<script>(function(){var el=document.getElementById("ih-abar-cd");if(!el)return;'
		. 'var t=+el.getAttribute("data-t"),p=function(n){return("0"+n).slice(-2)};'
		. 'var f=function(){var d=t-Date.now();if(d<0)d=0;var s=Math.floor(d/1000);'
		. 'el.textContent=Math.floor(s/86400)+"d "+p(Math.floor((s%86400)/3600))+":"+p(Math.floor((s%3600)/60))+":"+p(s%60);};'
		. 'f();setInterval(f,1000);})();</script>';
}
add_action( 'admin_footer', 'ih247_wpim_admin_bar_script' );
add_action( 'wp_footer', 'ih247_wpim_admin_bar_script' );
