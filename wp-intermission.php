/**
 * Optional per-site override folder (developer feature). If
 * wp-content/wp-intermission/template.html exists, template mode uses it
 * instead of the bundled template, and {{ASSETS_URL}} points at that folder.
 * Most sites never need this — "Full custom HTML" mode does everything from
 * the admin screen with no filesystem access.
 */
define( 'IH247_WPIM_OVERRIDE_DIR', WP_CONTENT_DIR . '/wp-intermission' );

/* -------------------------------------------------------------------------
 * Template + content resolution
 * ---------------------------------------------------------------------- */

function ih247_wpim_template_path() {
	$override = IH247_WPIM_OVERRIDE_DIR . '/template.html';
	$path     = file_exists( $override ) ? $override : __DIR__ . '/templates/template.html';
	return apply_filters( 'ihelp247_wp_intermission_template_path', $path );
}

function ih247_wpim_assets_url() {
	$override = IH247_WPIM_OVERRIDE_DIR . '/template.html';
	if ( file_exists( $override ) ) {
		$url = content_url( 'wp-intermission' );
	} else {
		// Default: a dedicated folder inside uploads — survives plugin, theme,
		// and core updates, and resolves to the same relative path on every
		// site, so fleet-shared HTML using {{ASSETS_URL}} is portable.
		$uploads = wp_get_upload_dir();
		$url     = untrailingslashit( $uploads['baseurl'] ) . '/wp-intermission';
	}
	return apply_filters( 'ihelp247_wp_intermission_assets_url', $url );
}

/** Make sure the uploads asset folder exists so FTP/Media drops have a home. */
function ih247_wpim_ensure_asset_dir() {
	$uploads = wp_get_upload_dir();
	wp_mkdir_p( untrailingslashit( $uploads['basedir'] ) . '/wp-intermission' );
}

