function ih247_wpim_sanitize_designer( $in ) {
	$out = ih247_wpim_designer_defaults();
	$in  = is_array( $in ) ? $in : array();

	foreach ( array( 'bg_url', 'logo_url' ) as $k ) {
		if ( isset( $in[ $k ] ) ) {
			$out[ $k ] = esc_url_raw( trim( (string) $in[ $k ] ) );
		}
	}
	$inline = array( 'strong' => array(), 'em' => array(), 'b' => array(), 'i' => array(), 'u' => array(), 'br' => array(), 'a' => array( 'href' => true, 'target' => true ) );
	foreach ( array( 'title', 'subtitle' ) as $k ) {
		if ( isset( $in[ $k ] ) ) {
			$out[ $k ] = wp_kses( (string) $in[ $k ], $inline );
		}
	}
	$stacks = ih247_wpim_system_stacks();
	foreach ( array( 'heading', 'body', 'cd', 'footer' ) as $slot ) {
		if ( isset( $in[ $slot . '_source' ] ) && in_array( $in[ $slot . '_source' ], array( 'system', 'google', 'custom', 'inherit' ), true ) ) {
			$out[ $slot . '_source' ] = $in[ $slot . '_source' ];
		}
		if ( isset( $in[ $slot . '_stack' ] ) && isset( $stacks[ $in[ $slot . '_stack' ] ] ) ) {
			$out[ $slot . '_stack' ] = $in[ $slot . '_stack' ];
		}
		foreach ( array( '_google', '_family' ) as $suffix ) {
			if ( isset( $in[ $slot . $suffix ] ) ) {
				$out[ $slot . $suffix ] = sanitize_text_field( (string) $in[ $slot . $suffix ] );
			}
		}
		if ( isset( $in[ $slot . '_url' ] ) ) {
			$out[ $slot . '_url' ] = esc_url_raw( trim( (string) $in[ $slot . '_url' ] ) );
		}
	}
	foreach ( array( 'text', 'disclaimer' ) as $k ) {
		if ( isset( $in[ $k ] ) ) {
			$out[ $k ] = wp_kses_post( (string) $in[ $k ] );
		}
	}
	foreach ( array( 'title_size', 'subtitle_size', 'text_size' ) as $k ) {
		if ( isset( $in[ $k ] ) ) {
			$out[ $k ] = max( 8, min( 160, absint( $in[ $k ] ) ) );
		}
	}
	foreach ( array( 'title_color', 'subtitle_color', 'text_color', 'cd_color', 'bg_color', 'bg_color2' ) as $k ) {
		if ( isset( $in[ $k ] ) ) {
			$hex = sanitize_hex_color( (string) $in[ $k ] );
			if ( $hex ) {
				$out[ $k ] = $hex;
			}
		}
	}
	if ( isset( $in['bg_style'] ) && in_array( $in['bg_style'], array( 'default', 'solid', 'gradient' ), true ) ) {
		$out['bg_style'] = $in['bg_style'];
	}
	if ( isset( $in['bg_dir'] ) && in_array( $in['bg_dir'], array( 'radial', 'vertical', 'diagonal' ), true ) ) {
		$out['bg_dir'] = $in['bg_dir'];
	}
	$out['bg_overlay'] = ! empty( $in['bg_overlay'] ) ? '1' : '';
	if ( isset( $in['bg_glass_op'] ) ) {
		$out['bg_glass_op'] = max( 10, min( 100, absint( $in['bg_glass_op'] ) ) );
	}
	if ( isset( $in['cd_shape'] ) && in_array( $in['cd_shape'], array( 'square', 'rounded', 'circle' ), true ) ) {
		$out['cd_shape'] = $in['cd_shape'];
	}
	return $out;
}

/** hex (#rrggbb) → rgba() string. */
function ih247_wpim_hex_rgba( $hex, $alpha ) {
	$hex = ltrim( (string) $hex, '#' );
	if ( 3 === strlen( $hex ) ) {
		$hex = $hex[0] . $hex[0] . $hex[1] . $hex[1] . $hex[2] . $hex[2];
	}
	if ( 6 !== strlen( $hex ) ) {
		$hex = 'ffffff';
	}
	return 'rgba(' . hexdec( substr( $hex, 0, 2 ) ) . ',' . hexdec( substr( $hex, 2, 2 ) ) . ',' . hexdec( substr( $hex, 4, 2 ) ) . ',' . $alpha . ')';
}

/** Resolve one font slot to a CSS stack; appends any needed link/@font-face markup. */
function ih247_wpim_resolve_slot_font( $d, $slot, &$links, &$faces ) {
	$stacks = ih247_wpim_system_stacks();
	$stack  = $stacks['system-ui']['css'];
	$src    = isset( $d[ $slot . '_source' ] ) ? $d[ $slot . '_source' ] : 'system';

	if ( 'inherit' === $src ) {
		// Follow the body font (guard: body itself never inherits).
		return 'body' === $slot ? $stack : ih247_wpim_resolve_slot_font( $d, 'body', $links, $faces );
	}

	if ( 'system' === $src && isset( $stacks[ $d[ $slot . '_stack' ] ] ) ) {
		$stack = $stacks[ $d[ $slot . '_stack' ] ]['css'];
	} elseif ( 'google' === $src && '' !== trim( $d[ $slot . '_google' ] ) ) {
		$fam = trim( $d[ $slot . '_google' ] );
		if ( false === strpos( $links, 'fonts.googleapis.com">' ) ) {
			$links .= '<link rel="preconnect" href="https://fonts.googleapis.com">'
				. '<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>';
		}
		// No weight axis on purpose: css2 hard-errors if ANY requested weight
		// is missing from the family. Spaces must be '+', hence urlencode.
		$css2 = 'https://fonts.googleapis.com/css2?family=' . urlencode( $fam ) . '&display=swap';
		if ( false === strpos( $links, $css2 ) ) {
			$links .= '<link href="' . $css2 . '" rel="stylesheet">';
		}
		$stack = "'" . esc_attr( $fam ) . "', " . $stack;
	} elseif ( 'custom' === $src && $d[ $slot . '_url' ] && $d[ $slot . '_family' ] ) {
		$face = "@font-face{font-family:'" . esc_attr( $d[ $slot . '_family' ] ) . "';src:url('" . esc_url( $d[ $slot . '_url' ] ) . "') format('woff2');font-display:swap;}";
		if ( false === strpos( $faces, $face ) ) {
			$faces .= $face;
		}
		$stack = "'" . esc_attr( $d[ $slot . '_family' ] ) . "', " . $stack;
	}
	return $stack;
}

/** Render the Designer fields into a complete HTML document. */
function ih247_wpim_designer_html( $d, $cd_ts = null, $cd_end = null ) {
	$font_face  = '';
	$head_links = '';

	// Resolve each font slot (heading = title; body = everything else).
	$heading_stack = ih247_wpim_resolve_slot_font( $d, 'heading', $head_links, $font_face );
	$font_stack    = ih247_wpim_resolve_slot_font( $d, 'body', $head_links, $font_face );
	$footer_stack  = ih247_wpim_resolve_slot_font( $d, 'footer', $head_links, $font_face );

	// Background: style base (stock gradient / solid / custom gradient), image
	// layered over it when set, overlay+glass controlled by their own toggle.
	$c1 = esc_attr( $d['bg_color'] ? $d['bg_color'] : '#000510' );
	$c2 = esc_attr( $d['bg_color2'] ? $d['bg_color2'] : '#0a2540' );
	if ( 'solid' === $d['bg_style'] ) {
		$base_layer = 'linear-gradient(' . $c1 . ',' . $c1 . ')'; // gradient-wrapped so it can stack under an image
	} elseif ( 'gradient' === $d['bg_style'] ) {
		if ( 'vertical' === $d['bg_dir'] ) {
			$base_layer = 'linear-gradient(180deg, ' . $c2 . ' 0%, ' . $c1 . ' 100%)';
		} elseif ( 'diagonal' === $d['bg_dir'] ) {
			$base_layer = 'linear-gradient(135deg, ' . $c2 . ' 0%, ' . $c1 . ' 100%)';
		} else {
			$base_layer = 'radial-gradient(circle at 50% 35%, ' . $c2 . ' 0%, ' . $c1 . ' 70%)';
		}
	} else {
		$base_layer = 'radial-gradient(circle at 50% 35%, #0a2540 0%, #000510 70%)';
	}
	$bg_layer = $d['bg_url']
		? "url('" . esc_url( $d['bg_url'] ) . "') no-repeat center center/cover, " . $base_layer
		: $base_layer;
	$body_bg  = 'default' === $d['bg_style'] ? '#000510' : $c1;
	$flat_bg  = '' === $d['bg_overlay']; // overlay+glass off

	$logo = $d['logo_url']
		? '<img src="' . esc_url( $d['logo_url'] ) . '" alt="" class="logo" onerror="this.style.display=\'none\'">'
		: '';

	$subtitle = '' !== trim( $d['subtitle'] )
		? '<p class="sub" style="font-size:' . (int) $d['subtitle_size'] . 'px;color:' . esc_attr( $d['subtitle_color'] ) . ';">' . $d['subtitle'] . '</p>'
		: '';

	$countdown = ih247_wpim_countdown_html( $d, $cd_ts, $cd_end ); // pass through so unsaved preview edits render

	$disclaimer = '' !== trim( $d['disclaimer'] )
		? '<div class="disclaimer">' . nl2br( $d['disclaimer'] ) . '</div>'
		: '';

	return '<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<meta name="robots" content="noindex">
<title>{{SITE_NAME}}</title>
' . $head_links . '
<style>
' . $font_face . '
* { margin: 0; padding: 0; box-sizing: border-box; }
body { height: 100vh; font-family: ' . $font_stack . '; color: #fff; overflow: hidden; background: ' . $body_bg . '; }
.bg { position: fixed; width: 100%; height: 100%; background: ' . $bg_layer . '; z-index: -3; animation: slowZoom 30s ease-in-out infinite alternate; }
@keyframes slowZoom { from { transform: scale(1); } to { transform: scale(1.05); } }
.overlay { position: fixed; width: 100%; height: 100%; background: radial-gradient(circle at center, rgba(0,20,40,0.4), rgba(0,5,15,0.9)), linear-gradient(to bottom, rgba(0,0,0,0.4), rgba(0,0,0,0.85)); z-index: -2; }
.glass { position: fixed; width: 100%; height: 100%; backdrop-filter: blur(2px); z-index: -1; }
.container { height: 100%; display: flex; justify-content: center; align-items: center; text-align: center; flex-direction: column; padding: 20px; animation: fadeIn 1.2s ease; }
.logo { width: 320px; max-width: 80%; margin-bottom: 40px; filter: drop-shadow(0 0 30px rgba(255,255,255,0.15)) drop-shadow(0 0 60px rgba(0,150,255,0.1)); }
h1 { font-family: ' . $heading_stack . '; font-weight: 500; letter-spacing: 1.2px; margin-bottom: 14px; }
.line { width: 70px; height: 2px; margin: 18px auto; background: linear-gradient(90deg, transparent, rgba(255,255,255,0.6), transparent); }
.container p { max-width: 560px; line-height: 1.5; }
.sub { margin-bottom: 6px; }
.footer { position: absolute; bottom: 25px; left: 0; right: 0; text-align: center; font-size: 12px; color: rgba(255,255,255,0.5); letter-spacing: 0.5px; font-family: ' . $footer_stack . '; }
.disclaimer { max-width: 640px; margin: 8px auto 0; font-size: 11px; line-height: 1.5; color: rgba(255,255,255,0.35); }
@keyframes fadeIn { from { opacity: 0; transform: translateY(12px); } to { opacity: 1; transform: translateY(0); } }
</style>
</head>
<body>
<div class="bg"></div>
' . ( $flat_bg ? '' : '<div class="overlay" style="opacity:' . ( max( 10, min( 100, (int) $d['bg_glass_op'] ) ) / 100 ) . ';"></div>
<div class="glass"></div>' ) . '
<div class="container">
' . $logo . '
<h1 style="font-size:' . (int) $d['title_size'] . 'px;color:' . esc_attr( $d['title_color'] ) . ';">' . $d['title'] . '</h1>
<div class="line"></div>
' . $subtitle . $countdown . '
<p style="font-size:' . (int) $d['text_size'] . 'px;color:' . esc_attr( $d['text_color'] ) . ';margin-top:18px;">' . nl2br( $d['text'] ) . '</p>
</div>
<div class="footer">
&copy; {{YEAR}} {{SITE_NAME}}
' . $disclaimer . '
</div>
</body>
</html>';
}

/** Allow self-hosted font uploads through the Media Library (admins only). */
function ih247_wpim_font_mimes( $mimes ) {
	if ( current_user_can( 'manage_options' ) ) {
		$mimes['woff']  = 'font/woff';
		$mimes['woff2'] = 'font/woff2';
	}
	return $mimes;
}
add_filter( 'upload_mimes', 'ih247_wpim_font_mimes' );

/** Live preview endpoint for the settings page (unsaved field values). */
function ih247_wpim_designer_preview_ajax() {
	check_ajax_referer( 'ih247_wpim_preview', 'nonce' );
	if ( ! current_user_can( 'manage_options' ) ) {
		wp_die( '', '', 403 );
	}
	$d = ih247_wpim_sanitize_designer( wp_unslash( isset( $_POST['d'] ) ? (array) $_POST['d'] : array() ) );

	// Unsaved countdown state comes along too, so date/enable/end changes preview live.
	$cd_on  = ! empty( $_POST['cd_on'] );
	$cd_ts  = $cd_on ? ih247_wpim_parse_cd( sanitize_text_field( wp_unslash( isset( $_POST['cd_target'] ) ? $_POST['cd_target'] : '' ) ) ) : 0;
	$cd_end = isset( $_POST['cd_end'] ) && in_array( $_POST['cd_end'], array( 'none', 'hide', 'golive' ), true ) ? $_POST['cd_end'] : 'none';

	header( 'Content-Type: text/html; charset=utf-8' );
	echo ih247_wpim_apply_tokens( ih247_wpim_designer_html( $d, $cd_ts, $cd_end ) ); // phpcs:ignore WordPress.Security.EscapeOutput
	wp_die();
}
