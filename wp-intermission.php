 * Countdown — {ihelp-wp-countdown} token
 * ---------------------------------------------------------------------- */

/** Parse a 'YYYY-MM-DDTHH:MM' string in the site timezone → timestamp, or 0. */
function ih247_wpim_parse_cd( $raw ) {
	$raw = trim( (string) $raw );
	if ( '' === $raw ) {
		return 0;
	}
	try {
		$dt = new DateTimeImmutable( $raw, wp_timezone() );
		return $dt->getTimestamp();
	} catch ( Exception $e ) {
		return 0;
	}
}

/** Is the countdown feature enabled? */
function ih247_wpim_cd_enabled() {
	return (bool) get_option( IH247_WPIM_OPT_CD_ON, false );
}

/** What happens at zero: 'none' | 'hide' | 'golive'. */
function ih247_wpim_cd_end() {
	$v = get_option( IH247_WPIM_OPT_CD_END, 'none' );
	return in_array( $v, array( 'none', 'hide', 'golive' ), true ) ? $v : 'none';
}

/** Target timestamp (site timezone) — 0 when the feature is off, unset, or invalid. */
function ih247_wpim_countdown_ts() {
	if ( ! ih247_wpim_cd_enabled() ) {
		return 0;
	}
	return ih247_wpim_parse_cd( get_option( IH247_WPIM_OPT_COUNTDOWN, '' ) );
}

/** Markup + CSS + JS replacing the countdown token. Empty string if no target set.
 *  $d / $ts / $end override saved values — the live preview passes unsaved
 *  fields through, so changes render without a save. */
function ih247_wpim_countdown_html( $d = null, $ts = null, $end = null ) {
	if ( null === $ts ) {
		$ts = ih247_wpim_countdown_ts();
	}
	if ( ! $ts ) {
		return '';
	}
	if ( null === $end ) {
		$end = ih247_wpim_cd_end();
	}
	$ms = $ts * 1000;

	$cells = '';
	foreach ( array( 'Days', 'Hours', 'Minutes', 'Seconds' ) as $label ) {
		$cells .= '<span class="ih-cd-cell"><b>--</b><i>' . $label . '</i></span>';
	}

	// Style options (set in Designer, honored in every mode the token runs in).
	if ( null === $d ) {
		$d = ih247_wpim_designer();
	}
	$links   = '';
	$faces   = '';
	$cd_font = ih247_wpim_resolve_slot_font( $d, 'cd', $links, $faces );
	$c      = $d['cd_color'] ? $d['cd_color'] : '#ffffff';
	$shape  = '';
	if ( 'rounded' === $d['cd_shape'] ) {
		$shape = '.ih-cd-cell{border-radius:12px;}';
	} elseif ( 'circle' === $d['cd_shape'] ) {
		$shape = '.ih-cd-cell{width:88px;height:88px;min-width:0;padding:0;border-radius:50%;justify-content:center;}'
			. '.ih-cd-cell b{font-size:24px;}'
			. '@media(max-width:480px){.ih-cd-cell{width:64px;height:64px;}.ih-cd-cell b{font-size:18px;}}';
	}

	return ( $links ? $links : '' )
		. '<div class="ih-cd" data-t="' . esc_attr( $ms ) . '" data-end="' . esc_attr( $end ) . '">' . $cells . '</div>'
		. '<style>'
		. ( $faces ? $faces : '' )
		. '.ih-cd{display:flex;gap:14px;justify-content:center;margin:26px auto 0;font-family:' . $cd_font . ';}'
		. '.ih-cd-cell{display:flex;flex-direction:column;align-items:center;min-width:74px;padding:14px 10px;'
		. 'border:1px solid ' . ih247_wpim_hex_rgba( $c, 0.35 ) . ';background:' . ih247_wpim_hex_rgba( $c, 0.07 ) . ';backdrop-filter:blur(6px);}'
		. '.ih-cd-cell b{font-size:28px;font-weight:600;letter-spacing:1px;font-variant-numeric:tabular-nums;color:' . esc_attr( $c ) . ';}'
		. '.ih-cd-cell i{font-style:normal;font-size:10px;letter-spacing:2px;text-transform:uppercase;'
		. 'color:' . ih247_wpim_hex_rgba( $c, 0.6 ) . ';margin-top:6px;}'
		. '@media(max-width:480px){.ih-cd{gap:8px}.ih-cd-cell{min-width:58px;padding:10px 6px}.ih-cd-cell b{font-size:20px}}'
		. $shape
		. '</style>'
		. '<script>(function(){if(window.ihCd)return;window.ihCd=1;'
		. 'var armed=false,fired=false;'
		. 'var tick=function(){var els=document.querySelectorAll(".ih-cd");'
		. 'for(var j=0;j<els.length;j++){var el=els[j],d=+el.getAttribute("data-t")-Date.now();'
		. 'if(d>0)armed=true;if(d<0)d=0;'
		. 'var s=Math.floor(d/1000),v=[Math.floor(s/86400),Math.floor((s%86400)/3600),Math.floor((s%3600)/60),s%60],'
		. 'b=el.querySelectorAll("b");for(var i=0;i<4;i++){b[i].textContent=("0"+v[i]).slice(-2);}'
		// At zero, honor the configured end behavior: 'hide' removes the counter;
		// 'golive' reloads once ~2s later (armed guard: pages that load with the
		// target already past never reload, so no refresh loops); 'none' shows 00s.
		. 'var e=el.getAttribute("data-end");'
		. 'if(0===d&&"hide"===e){el.style.display="none";}'
		. 'if(0===d&&"golive"===e&&armed&&!fired){fired=true;setTimeout(function(){location.reload();},2000);}}};'
		. 'tick();setInterval(tick,1000);})();</script>';
}

/* -------------------------------------------------------------------------
 * Page build — one function renders the final HTML for every consumer
 * (front-end response, preview, and the generated core-update drop-in).
 * ---------------------------------------------------------------------- */

/** Token substitution shared by both modes. */
function ih247_wpim_apply_tokens( $html ) {
	$cd   = ih247_wpim_countdown_html();
	$html = str_replace( IH247_WPIM_COUNTDOWN_TOKEN, $cd, $html );
	$html = str_replace(
		array( '{{ASSETS_URL}}', '{{SITE_NAME}}', '{{YEAR}}' ),
		array( esc_url( ih247_wpim_assets_url() ), esc_html( get_bloginfo( 'name' ) ), gmdate( 'Y' ) ),
		$html
	);
	return $html;
}

/** Small iHelp247 link, bottom-right of the served page. One checkbox on the
 *  settings page removes it — free either way, no strings attached. Injected
 *  just before </body> in every mode; documents without </body> are left alone. */
function ih247_wpim_inject_credit( $html ) {
	if ( get_option( IH247_WPIM_OPT_HIDE_CREDIT, false ) ) {
		return $html;
	}
	$credit = '<a href="' . esc_url( IH247_WPIM_PROJECTS_URL ) . '" target="_blank" rel="noopener nofollow"'
		. ' style="position:fixed;right:14px;bottom:10px;z-index:9;font-family:-apple-system,BlinkMacSystemFont,\'Segoe UI\',Roboto,sans-serif;'
		. 'font-size:11px;letter-spacing:.4px;color:inherit;opacity:.35;text-decoration:none;">'
		. esc_html__( 'intermission by iHelp247', 'wp-intermission' ) . '</a>';
	$pos = strripos( $html, '</body>' );
	return false === $pos ? $html : substr_replace( $html, $credit . "\n", $pos, 0 );
}

function ih247_wpim_build_html() {
	$mode = ih247_wpim_get_mode();

	if ( 'designer' === $mode ) {
		return apply_filters( 'ihelp247_wp_intermission_html', ih247_wpim_inject_credit( ih247_wpim_apply_tokens( ih247_wpim_designer_html( ih247_wpim_designer() ) ) ) );
	}

	if ( 'full' === $mode ) {
		$html = (string) get_option( IH247_WPIM_OPT_FULL, '' );
		if ( '' !== trim( $html ) ) {
			return apply_filters( 'ihelp247_wp_intermission_html', ih247_wpim_inject_credit( ih247_wpim_apply_tokens( $html ) ) );
		}
		// Fall through to template mode if full HTML is empty — never serve a blank page.
	}

	$template = ih247_wpim_template_path();
	if ( ! is_readable( $template ) ) {
		return '';
	}
	$html = file_get_contents( $template );

	// Inject editor content. Custom templates without {{CONTENT}} still work as-is.
	if ( false !== strpos( $html, '{{CONTENT}}' ) ) {
		$html = str_replace( '{{CONTENT}}', ih247_wpim_get_content(), $html );
	}

	return apply_filters( 'ihelp247_wp_intermission_html', ih247_wpim_inject_credit( ih247_wpim_apply_tokens( $html ) ) );
}

/* -------------------------------------------------------------------------
 * Front-end: serve the maintenance page
 * ---------------------------------------------------------------------- */

function ih247_wpim_is_enabled() {
	return (bool) get_option( IH247_WPIM_OPTION, false );
}

function ih247_wpim_should_bypass() {
	$bypass = current_user_can( IH247_WPIM_CAPABILITY );
	if ( $bypass && isset( $_GET['ihelp247_wp_intermission_preview'] ) ) {
		$bypass = false; // Logged-in editors can force-preview.
	}
	return apply_filters( 'ihelp247_wp_intermission_bypass', $bypass );
}

function ih247_wpim_maybe_serve() {
	$preview = isset( $_GET['ihelp247_wp_intermission_preview'] ) && current_user_can( IH247_WPIM_CAPABILITY );

	// Countdown end behavior 'golive': server-side auto-disable. Otherwise the
	// countdown is display-only — reaching zero changes nothing.
	if ( ih247_wpim_is_enabled() && 'golive' === ih247_wpim_cd_end() ) {
		$ts = ih247_wpim_countdown_ts();
		if ( $ts && time() >= $ts ) {
			update_option( IH247_WPIM_OPTION, false ); // maintenance ends itself at T-0
		}
	}

	if ( ! ih247_wpim_is_enabled() && ! $preview ) {
		return;
	}
	if ( is_admin() || wp_doing_ajax() || wp_doing_cron() ) {
		return; // Never block wp-admin, AJAX, or cron. wp-login is untouched by design.
	}
	if ( ! $preview && ih247_wpim_should_bypass() ) {
		return;
	}

	$html = ih247_wpim_build_html();
	if ( '' === $html ) {
		return; // Fail open: a missing template must never white-screen the site.
	}

	$status = ih247_wpim_get_status();

	nocache_headers();
	status_header( $status );
	if ( 503 === $status ) {
		header( 'Retry-After: ' . absint( IH247_WPIM_RETRY_AFTER ) );
	}
	header( 'Content-Type: text/html; charset=utf-8' );
	echo $html; // phpcs:ignore WordPress.Security.EscapeOutput -- intentional raw template output.
	exit;
}
add_action( 'template_redirect', 'ih247_wpim_maybe_serve', 0 );

/* -------------------------------------------------------------------------
 * Core-update drop-in (wp-content/maintenance.php)
 *
 * While WordPress runs core/plugin/theme updates, plugins do not execute —
 * core serves wp-content/maintenance.php instead, if present. When the
 * checkbox is on, this plugin generates that file as a static snapshot of
 * the same page, and regenerates it on every settings save. Drop-ins are
 * outside the scope of core updates, so WP never overwrites it. The update
 * window is always genuinely temporary, so the drop-in always sends 503.
 * ---------------------------------------------------------------------- */

function ih247_wpim_dropin_path() {
	return WP_CONTENT_DIR . '/maintenance.php';
}

/** True when no drop-in exists, or the existing one is ours. */
function ih247_wpim_dropin_is_ours_or_absent() {
	$path = ih247_wpim_dropin_path();
	if ( ! file_exists( $path ) ) {
		return true;
	}
	$head = (string) file_get_contents( $path, false, null, 0, 512 );
	return false !== strpos( $head, IH247_WPIM_DROPIN_MARKER );
}

/** Foreign files are respected by default; the opt-in Force overwrite option
 *  replaces them on save. Unreliable by design: the file is only checked and
 *  replaced when settings are saved — it is not monitored, and the other tool
 *  can recreate its file at any time. */
function ih247_wpim_force_overwrite() {
	return (bool) get_option( IH247_WPIM_OPT_FORCE, false );
}

function ih247_wpim_write_dropin() {
	if ( ! ih247_wpim_dropin_is_ours_or_absent() && ! ih247_wpim_force_overwrite() ) {
		return false; // Never clobber a hand-made drop-in unless explicitly forced.
	}
	$html = ih247_wpim_build_html();
	if ( '' === $html ) {
		return false;
	}
	$php = "<?php\n"
		. '/* ' . IH247_WPIM_DROPIN_MARKER . ' v' . IH247_WPIM_VERSION . ' on ' . gmdate( 'c' ) . ".\n"
		. "   Do not edit — regenerated whenever the plugin's settings are saved. */\n"
		. "http_response_code( 503 ); // protocol-agnostic (HTTP/1.1 and HTTP/2 both correct)\n"
		. "header( 'Retry-After: " . absint( IH247_WPIM_RETRY_AFTER ) . "' );\n"
		. "header( 'Content-Type: text/html; charset=utf-8' );\n"
		. "?>" . $html;
	return false !== @file_put_contents( ih247_wpim_dropin_path(), $php );
}

function ih247_wpim_remove_dropin() {
	$path = ih247_wpim_dropin_path();
	if ( file_exists( $path ) && ih247_wpim_dropin_is_ours_or_absent() ) {
		@unlink( $path );
	}
}

/* ---- Database-failure drop-in (wp-content/db-error.php) -------------------
 * When WordPress cannot connect to the database, core serves
 * wp-content/db-error.php (if present) instead of the bare "Error
 * establishing a database connection" screen. Same generate/sync/marker
 * rules as the maintenance drop-in. It runs with NO WordPress loaded, so it
 * is a static snapshot; a timestamped HTML comment is appended so anyone
 * viewing source can tell a DB outage from planned maintenance. Leave the
 * checkbox OFF in environments where you want raw errors in your face. */

function ih247_wpim_dberror_path() {
	return WP_CONTENT_DIR . '/db-error.php';
}

function ih247_wpim_dberror_is_ours_or_absent() {
	$path = ih247_wpim_dberror_path();
	if ( ! file_exists( $path ) ) {
		return true;
	}
	$head = (string) file_get_contents( $path, false, null, 0, 512 );
	return false !== strpos( $head, IH247_WPIM_DROPIN_MARKER );
}

function ih247_wpim_write_dberror() {
	if ( ! ih247_wpim_dberror_is_ours_or_absent() && ! ih247_wpim_force_overwrite() ) {
		return false;
	}
	$html = ih247_wpim_build_html();
	if ( '' === $html ) {
		return false;
	}
	$html .= "\n<!-- iHelp247 WP Intermission: served by wp-content/db-error.php — the database was unreachable when this page was delivered. Snapshot generated " . gmdate( 'c' ) . '. -->';
	$php   = "<?php\n"
		. '/* ' . IH247_WPIM_DROPIN_MARKER . ' v' . IH247_WPIM_VERSION . ' on ' . gmdate( 'c' ) . " (db-error drop-in).\n"
		. "   Do not edit — regenerated whenever the plugin's settings are saved. */\n"
		. "http_response_code( 503 );\n"
		. "header( 'Retry-After: 300' );\n"
		. "header( 'Content-Type: text/html; charset=utf-8' );\n"
		. "?>" . $html;
	return false !== @file_put_contents( ih247_wpim_dberror_path(), $php );
}

function ih247_wpim_remove_dberror() {
	$path = ih247_wpim_dberror_path();
	if ( file_exists( $path ) && ih247_wpim_dberror_is_ours_or_absent() ) {
		@unlink( $path );
	}
}

function ih247_wpim_sync_dropin() {
	ih247_wpim_ensure_asset_dir();

	if ( get_option( IH247_WPIM_OPT_DROPIN, false ) ) {
		ih247_wpim_write_dropin();
	} else {
		ih247_wpim_remove_dropin();
	}

	if ( get_option( IH247_WPIM_OPT_DBERROR, false ) ) {
		ih247_wpim_write_dberror();
	} else {
		ih247_wpim_remove_dberror();
	}
}

/** Regenerate whenever any of our options change. */
function ih247_wpim_option_changed( $option ) {
	static $ours = null;
	if ( null === $ours ) {
		$ours = array(
			IH247_WPIM_OPTION,
			IH247_WPIM_OPT_MODE,
			IH247_WPIM_OPT_CONTENT,
			IH247_WPIM_OPT_FULL,
			IH247_WPIM_OPT_STATUS,
			IH247_WPIM_OPT_COUNTDOWN,
			IH247_WPIM_OPT_DROPIN,
			IH247_WPIM_OPT_CD_ON,
			IH247_WPIM_OPT_CD_END,
			IH247_WPIM_OPT_DBERROR,
			IH247_WPIM_OPT_FORCE,
			IH247_WPIM_OPT_HIDE_CREDIT,
		);
	}
	// Force overwrite implies core-update coverage (server-side backstop for
	// the settings-page JS): turning force on turns the drop-in on too.
	if ( IH247_WPIM_OPT_FORCE === $option && get_option( IH247_WPIM_OPT_FORCE, false ) && ! get_option( IH247_WPIM_OPT_DROPIN, false ) ) {
		update_option( IH247_WPIM_OPT_DROPIN, true );
	}

	if ( in_array( $option, $ours, true ) ) {
		ih247_wpim_sync_dropin();
	}
}
add_action( 'updated_option', 'ih247_wpim_option_changed' );
add_action( 'added_option', 'ih247_wpim_option_changed' );

